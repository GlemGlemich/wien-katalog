// Complete messages generated by the server, including saved import failures.
const serverTranslations = [
  [/^(\d+(?:[.,]\d+)?) (кг|г|мл|л)$/, (_, n, unit) => n.replace(',', '.') + ' ' + english[unit]],
  [/^От (\d+(?:[.,]\d+)?) шт\.(, цена за одну)?$/, (_, n, single) => `From ${n} items${single ? ', price per item' : ''}`],
  [/^Страница (\d+)(?: из (\d+))?$/, (_, page, total) => `Page ${page}${total ? ' of ' + total : ''}`],
  [/^Товары (\d+)–(\d+)$/, (_, from, to) => `Products ${from}–${to}`],
  [/^Получено (\d+) из (\d+)\. Каталог мог измениться во время загрузки; повторите обновление\.$/, (_, received, total) => `Received ${received} of ${total}. The catalogue may have changed during the download; refresh again.`],
  [/^Сайт магазина ответил HTTP (\d+)\. Сохранённые цены остаются доступны\.$/, (_, code) => `The store returned HTTP ${code}. Saved prices remain available.`],
  [/^Сайт магазина недоступен для чтения \(HTTP (\d+)\)\. Попробуйте позже или откройте его напрямую\.$/, (_, code) => `The store website cannot be read (HTTP ${code}). Try later or open it directly.`],
];

function t(key, ...values) {
  if (typeof key !== 'string') return key;
  let result = key;
  if (language === 'en') {
    if (Object.hasOwn(english, key)) result = english[key];
    else for (const [pattern, replacement] of serverTranslations) {
      if (pattern.test(key)) { result = key.replace(pattern, replacement); break; }
    }
  }
  return values.length ? result.replace(/\{(\d+)\}/g, (match, index) => values[index] ?? match) : result;
}

function translatePage() {
  document.documentElement.lang = language;
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  for (const attr of ['aria-label', 'placeholder', 'title', 'content']) {
    document.querySelectorAll(`[data-i18n-${attr}]`).forEach(el => {
      el.setAttribute(attr, t(el.getAttribute('data-i18n-' + attr)));
    });
  }
  document.getElementById('language').value = language;
}

document.getElementById('language').addEventListener('change', event => {
  const next = event.target.value;
  if (!['ru', 'en'].includes(next) || next === language) return;
  language = next;
  try { localStorage.setItem(languageStorageKey, language); } catch { /* Optional persistence. */ }
  translatePage();
  window.dispatchEvent(new Event('languagechange'));
});
translatePage();
